// Builds database/seed.sql (sources, topics, starter articles) and
// database/setup.sql (structure + seed in one paste-able file).
// Run with: npm run make-setup-sql
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const db = (f) => join(root, "database", f);

// ---------- tiny CSV reader (handles quotes and commas inside quotes) ----------
export function parseCsv(text) {
  text = text.replace(/^﻿/, "");
  const rows = [];
  let row = [], field = "", inQuotes = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (inQuotes) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') inQuotes = false;
      else field += c;
    } else if (c === '"') inQuotes = true;
    else if (c === ",") { row.push(field); field = ""; }
    else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(field); field = "";
      if (row.some((v) => v !== "")) rows.push(row);
      row = [];
    } else field += c;
  }
  row.push(field);
  if (row.some((v) => v !== "")) rows.push(row);
  const [header, ...body] = rows;
  return body.map((r) => Object.fromEntries(header.map((h, i) => [h.trim(), (r[i] ?? "").trim()])));
}

const q = (v) => (v === null || v === undefined || v === "" ? "null" : `'${String(v).replace(/'/g, "''")}'`);

// ---------- sources ----------
const sources = readFileSync(db("sources.txt"), "utf8")
  .split("\n").map((l) => l.trim()).filter((l) => l && !l.startsWith("#"));

// The spreadsheet's source names, matched to the source list,
// plus co-publishers and details that belong in their own fields.
const fixes = {
  "1":  { source: "Appetite (Elsevier)" },
  "2":  { source: "Nature" },
  "3":  { source: "World Business Council for Sustainable Development (WBCSD)", related: "Deloitte Consulting LLP" },
  "4":  { source: "World Resources Institute" },
  "5":  { source: "Culinary Institute of America", related: "Menus of Change; Department of Nutrition, Harvard T.H. Chan School of Public Health" },
  "6":  { source: "United Nations Environment Programme (UNEP)", related: "Stockholm Environment Institute; Good Food Institute" },
  "7":  { source: "Greener by Default", related: "Farm Forward; Better Food Foundation" },
  "8":  { source: "Food and Agriculture Organization of the United Nations (FAO)", related: "FAO Commission on Genetic Resources for Food and Agriculture" },
  "9":  { source: "World Resources Institute" },
  "10": { source: "Knorr" },
  "11": { source: "The Lancet", details: "The Lancet 393 (10170): 447–492" },
  "12": { source: "Menus of Change University Research Collaborative" },
};

const articles = parseCsv(readFileSync(db("starter-articles.csv"), "utf8"));
const splitTags = (s) => s.split(";").map((t) => t.trim().toLowerCase()).filter(Boolean);

// Resources from the shared Drive folder (already in the right shape).
const driveItems = JSON.parse(readFileSync(db("drive-folder-articles.json"), "utf8"));

const topics = [...new Set([
  ...articles.flatMap((a) => splitTags(a.topic_tags)),
  ...driveItems.flatMap((d) => d.topics.map((t) => t.toLowerCase())),
])].sort();

let out = `-- ============================================================
-- The Seed: starting data (generated by scripts/build-setup-sql.mjs)
-- Safe to run more than once: nothing is duplicated.
-- ============================================================

-- Sources (${sources.length})
insert into public.sources (name) values
${sources.map((s) => `  (${q(s)})`).join(",\n")}
on conflict (name) do nothing;

-- Topics (${topics.length}), taken from the starter articles' tags
insert into public.topics (name) values
${topics.map((t) => `  (${q(t)})`).join(",\n")}
on conflict (name) do nothing;

-- Starter articles (${articles.length}), loaded straight into the library as approved
`;

for (const a of articles) {
  const fx = fixes[a.id];
  if (!fx) throw new Error(`No source match for starter article ${a.id}`);
  if (!sources.includes(fx.source)) throw new Error(`Source not in list: ${fx.source}`);
  out += `
insert into public.articles
  (url, title, authors, publication_year, publication_details, source_id, related_organizations,
   resource_type, summary, summary_origin, summary_needs_review, admin_notes, status, origin)
select ${q(a.drive_link)}, ${q(a.title)}, ${q(a.authors)}, ${a.year ? Number(a.year) : "null"}, ${q(fx.details)},
  (select id from public.sources where name = ${q(fx.source)}), ${q(fx.related)},
  ${q(a.resource_type)}, ${q(a.summary)}, ${a.summary ? "'ai_draft'" : "null"}, true, ${q(a.review_status)}, 'approved', 'import'
where not exists (select 1 from public.articles where url = ${q(a.drive_link)});

insert into public.article_topics (article_id, topic_id)
select a.id, t.id from public.articles a, public.topics t
where a.url = ${q(a.drive_link)} and t.name in (${splitTags(a.topic_tags).map(q).join(", ")})
on conflict do nothing;
`;
}

out += `\n-- Resources from the shared Drive folder (${driveItems.length}): published research goes in the library;\n-- BITE and Food for Climate League's own materials wait in the review queue.\n`;
for (const d of driveItems) {
  if (!sources.includes(d.source)) throw new Error(`Source not in list: ${d.source}`);
  out += `
insert into public.articles
  (url, title, authors, publication_year, publication_details, source_id, related_organizations,
   resource_type, summary, summary_origin, summary_needs_review, admin_notes, submission_note, status, origin)
select ${q(d.url)}, ${q(d.title)}, ${q(d.authors)}, ${d.year ?? "null"}, ${q(d.details)},
  (select id from public.sources where name = ${q(d.source)}), ${q(d.related)},
  ${q(d.resource_type)}, ${q(d.summary)}, 'ai_draft', true, ${q(d.notes)}, ${q(d.submission_note)}, ${q(d.status)}, 'import'
where not exists (select 1 from public.articles where url = ${q(d.url)});

insert into public.article_topics (article_id, topic_id)
select a.id, t.id from public.articles a, public.topics t
where a.url = ${q(d.url)} and t.name in (${d.topics.map((t) => q(t.toLowerCase())).join(", ")})
on conflict do nothing;
`;
}

writeFileSync(db("seed.sql"), out);
const schema = readFileSync(db("schema.sql"), "utf8");
writeFileSync(db("setup.sql"),
  `-- The Seed: complete setup. Paste this whole file into Supabase > SQL Editor and click Run.\n\n${schema}\n\n${out}`);
const approved = articles.length + driveItems.filter((d) => d.status === "approved").length;
console.log(`Wrote seed.sql and setup.sql: ${sources.length} sources, ${topics.length} topics, ` +
  `${approved} library articles, ${driveItems.length - (approved - articles.length)} waiting for review.`);
